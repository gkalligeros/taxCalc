    public static function compute(float $gross, string $countryCode): array
    {
        $countryCode = strtoupper($countryCode);

        $worldPercentile = self::interpolatePercentile($gross, self::$worldData);

        $countryAvailable = isset(self::$countryData[$countryCode]);
        $countryPercentile = $countryAvailable
            ? self::interpolatePercentile($gross, self::$countryData[$countryCode])
            : null;

        return [
            'world_percentile'    => round($worldPercentile, 1),
            'country_percentile'  => $countryPercentile !== null ? round($countryPercentile, 1) : null,
            'country_available'   => $countryAvailable,
            'world_distribution'  => self::toDistributionPoints(self::$worldData),
            'country_distribution' => $countryAvailable
                ? self::toDistributionPoints(self::$countryData[$countryCode])
                : null,
        ];
    }

    private static function interpolatePercentile(float $income, array $data): float
    {
        ksort($data);
        $percentiles = array_keys($data);
        $incomes     = array_values($data);
        $n           = count($incomes);

        if ($income <= $incomes[0]) {
            return 0.0;
        }

        if ($income >= $incomes[$n - 1]) {
            return 99.9;
        }

        for ($i = 1; $i < $n; $i++) {
            if ($income <= $incomes[$i]) {
                $ratio = ($income - $incomes[$i - 1]) / ($incomes[$i] - $incomes[$i - 1]);
                return $percentiles[$i - 1] + $ratio * ($percentiles[$i] - $percentiles[$i - 1]);
            }
        }

        return 99.9;
    }

    private static function toDistributionPoints(array $data): array
    {
        ksort($data);
        $points = [];
        foreach ($data as $percentile => $income) {
            $points[] = ['percentile' => $percentile, 'income' => $income];
        }
        return $points;
    }
